/* =====================================
   APPLICATION LANGUAGE
===================================== */

let currentLanguage = "es";
let lastCalculation = null;

const languageSelector =
    document.getElementById("languageSelector");


function translatePage() {

    const dictionary = translations[currentLanguage];

    document.documentElement.lang = currentLanguage;

    document.querySelectorAll("[data-i18n]").forEach(element => {

        const key = element.dataset.i18n;

        if (dictionary[key]) {
            element.textContent = dictionary[key];
        }

    });

    const paperInput = document.getElementById("paper");

    paperInput.placeholder =
        currentLanguage === "es"
            ? paperInput.dataset.placeholderEs
            : paperInput.dataset.placeholderEn;

    // Update existing results without recalculating

    if (lastCalculation) {
        renderResults(lastCalculation);
        updateCertificate(lastCalculation);
    }

}


languageSelector.addEventListener("change", function() {

    currentLanguage = this.value;

    translatePage();

});


/* =====================================
   EMISSION FACTORS AND ECO-POINTS
   ORIGINAL CALCULATIONS PRESERVED
===================================== */

// Weekly transportation emissions

const transportEmissions = {
    bus: 6,
    private: 18,
    shared: 9,
    bike: 0
};


// Transportation points

const transportPoints = {
    bus: 35,
    private: 15,
    shared: 40,
    bike: 50
};


// Paper emissions

const CO2_PER_SHEET = 0.005;


// Recycling reduction

const recyclingReduction = {
    low: 0,
    medium: 0.10,
    high: 0.20
};


// Recycling points

const recyclingPoints = {
    low: 0,
    medium: 10,
    high: 20
};


/* =====================================
   FORM SUBMISSION
===================================== */

const ecoForm = document.getElementById("ecoForm");

ecoForm.addEventListener("submit", function(event) {

    event.preventDefault();

    // Get form values

    const transport =
        document.getElementById("transport").value;

    const paper =
        Number(document.getElementById("paper").value);

    const recycling =
        document.getElementById("recycling").value;


    // Validate inputs

    if (
        !transport ||
        !recycling ||
        !Number.isInteger(paper) ||
        paper < 0 ||
        paper > 500
    ) {

        alert(translations[currentLanguage].validationMessage);

        return;
    }


    // 1. TRANSPORT EMISSIONS

    const transportCO2 =
        transportEmissions[transport];


    // 2. PAPER EMISSIONS

    const weeklyPaper = paper * 5;

    const paperCO2 =
        weeklyPaper * CO2_PER_SHEET;


    // 3. RECYCLING REDUCTION

    const reduction =
        recyclingReduction[recycling];

    const adjustedPaperCO2 =
        paperCO2 * (1 - reduction);


    // 4. TOTAL CARBON FOOTPRINT

    const totalCO2 =
        transportCO2 + adjustedPaperCO2;


    // 5. PAPER ECO-POINTS

    const paperScore = Math.max(
        0,
        30 - (paper * 3)
    );


    // 6. TOTAL ECO-POINTS

    const totalPoints =
        transportPoints[transport] +
        paperScore +
        recyclingPoints[recycling];


    // Save calculation

    lastCalculation = {
        transport,
        paper,
        recycling,
        totalCO2,
        totalPoints
    };


    // Display results

    renderResults(lastCalculation);

    updateCertificate(lastCalculation);

    document.getElementById("results").style.display = "block";

});


/* =====================================
   DISPLAY RESULTS
===================================== */

function renderResults(data) {

    const dictionary = translations[currentLanguage];

    document.getElementById("co2Result").textContent =
        data.totalCO2.toFixed(2) + " kg CO₂";

    document.getElementById("pointsResult").textContent =
        data.totalPoints + " / 100";


    const evaluation =
        document.getElementById("evaluation");

    const message =
        document.getElementById("message");


    if (data.totalPoints >= 80) {

        evaluation.textContent = dictionary.excellentTitle;
        message.textContent = dictionary.excellentMessage;

    } else if (data.totalPoints >= 60) {

        evaluation.textContent = dictionary.goodTitle;
        message.textContent = dictionary.goodMessage;

    } else if (data.totalPoints >= 40) {

        evaluation.textContent = dictionary.improveTitle;
        message.textContent = dictionary.improveMessage;

    } else {

        evaluation.textContent = dictionary.actionTitle;
        message.textContent = dictionary.actionMessage;

    }

}


/* =====================================
   CERTIFICATE CONTENT
===================================== */

function updateCertificate(data) {

    const dictionary = translations[currentLanguage];

    const transportNames = {
        bus: dictionary.busCertificate,
        private: dictionary.privateCertificate,
        shared: dictionary.sharedCertificate,
        bike: dictionary.bikeCertificate
    };

    const recyclingNames = {
        low: dictionary.lowCertificate,
        medium: dictionary.mediumCertificate,
        high: dictionary.highCertificate
    };


    document.getElementById("certificatePoints").textContent =
        data.totalPoints + " / 100";

    document.getElementById("certificateCO2").textContent =
        data.totalCO2.toFixed(2) + " kg CO₂";

    document.getElementById("certificateTransportValue").textContent =
        transportNames[data.transport];

    document.getElementById("certificatePaperValue").textContent =
        data.paper;

    document.getElementById("certificateRecyclingValue").textContent =
        recyclingNames[data.recycling];


    const locale =
        currentLanguage === "es" ? "es-CO" : "en-US";

    document.getElementById("certificateDateValue").textContent =
        new Date().toLocaleDateString(locale, {
            year: "numeric",
            month: "long",
            day: "numeric"
        });


    document.getElementById("certificateMessage").textContent =
        document.getElementById("message").textContent;

}


/* =====================================
   PRINT AND SAVE AS PDF
===================================== */

function openPrintDialog() {

    if (!lastCalculation) {
        return;
    }

    updateCertificate(lastCalculation);

    window.print();

}


document.getElementById("printButton").addEventListener(
    "click",
    openPrintDialog
);


document.getElementById("pdfButton").addEventListener(
    "click",
    openPrintDialog
);


/* =====================================
   INITIALIZE APPLICATION
===================================== */

translatePage();
